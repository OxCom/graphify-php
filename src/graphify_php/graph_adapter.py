"""`NodeIndex` and `EdgeSink` over graphify's in-memory `all_nodes` / `all_edges`.

This module is the only place that knows graphify's node and edge schema. Everything else in
the package talks to the two protocols in `ports`, so a schema move between graphify releases
is repaired here and nowhere else.

The schema this is written against, read from a real build of the reference application
(6302 nodes / 17886 links, 4012 of them from `.php` files):

- a class node carries `_callable_class: true` and a `label` that is the SHORT class name
  (`AbstractFrontController`), never the FQN, so an FQN has to be matched down to its last
  segment and then re-checked against the file path;
- a method node hangs off its class by a `method` edge and its label is `.methodName()`;
- a class node hangs off its file node by a `contains` edge;
- `_origin` is `ast` or `semantic` on both nodes and edges.
"""

from __future__ import annotations

import hashlib
import inspect
import os
import re

from .ports import CallTarget, Confidence, EngineCall, MethodBoundCall

# The marker this package stamps on every edge it adds, so a reader can select ours, count them,
# or drop them from a published graph without re-running the build.
#
# Deliberately NOT `_origin`: graphify overwrites that on every edge with `"ast"` after the
# resolvers run (extract.py:8285-8289), and it means the eviction tier, not the author. Our
# edges are regenerated by the AST pass, so `ast` is the right tier for them and claiming that
# key would both be lost and be wrong. A key of our own survives untouched.
EDGE_MARKER = "_resolver"
EDGE_ORIGIN = "graphify-php"

# graphify's own scores for the two confidence levels (extract.py:3534). Matching them keeps
# our edges comparable with graphify's in any consumer that ranks by score.
_CONFIDENCE_SCORE = {Confidence.EXTRACTED: 1.0, Confidence.INFERRED: 0.8}


def _key(label: str) -> str:
    """graphify's own label normalisation (extract.py), reproduced so keys agree.

    `.getCurrentUser()` and `getcurrentuser` collapse to the same key, which is what makes a
    method label from the graph comparable with a method name from PHP source.
    """
    return re.sub(r"[^a-zA-Z0-9]+", "", str(label)).lower()


def _fqn_parts(class_fqn: str) -> list[str]:
    return [p for p in str(class_fqn).replace("/", "\\").split("\\") if p]


def _path_parts(source_file: str) -> list[str]:
    stripped = re.sub(r"\.[^./\\]+$", "", str(source_file or ""))
    return [p for p in stripped.replace("\\", "/").split("/") if p]


def _tail_overlap(a: list[str], b: list[str]) -> int:
    """How many trailing segments the two paths share, compared normalised."""
    count = 0
    # Paths differ in length on purpose; the overlap stops at the shorter one.
    for left, right in zip(reversed(a), reversed(b), strict=False):
        if _key(left) != _key(right):
            break
        count += 1
    return count


_LINE = re.compile(r"\d+")


def _line(location: object) -> int | None:
    """The line in graphify's `L10` location, or None."""
    found = _LINE.search(str(location or ""))
    return int(found.group()) if found else None


def _name(node: dict) -> str:
    # `.format()` on a class method, `format()` on one whose class node was lost.
    return str(node.get("label", "")).strip(". ()")


def _real(path: str, repo_root: str) -> str:
    """One spelling per file: graphify's absolute build paths, PHPStan's, a relative one."""
    return os.path.realpath(path if os.path.isabs(path) else os.path.join(repo_root, path))


# A class method's label: `.format()`. A function or an anonymous class's method has no dot.
_DOTTED_METHOD = re.compile(r"^\.[A-Za-z_\x80-\uffff][A-Za-z0-9_\x80-\uffff]*\(\)$")


def _is_closure(node: dict) -> bool:
    # graphify labels closures and arrow functions `{closure#N}()`.
    return str(node.get("label", "")).startswith("{closure")


class GraphNodeIndex:
    """Answers "which node is method M of class C" and nothing else.

    Built once per resolver run: the walk is linear in nodes plus edges, and the resolver asks
    this question once per eligible call site, of which the reference application has thousands.
    """

    def __init__(self, all_nodes: list[dict], all_edges: list[dict]) -> None:
        node_by_id: dict[str, dict] = {}
        for node in all_nodes:
            nid = node.get("id")
            if nid:
                node_by_id[nid] = node

        # Only a class a file actually contains is a candidate. graphify also carries nodes
        # that no file contains (synthesised, external, semantic); binding a call to one of
        # those invents a target that has no definition to jump to.
        contained: set[str] = set()
        for edge in all_edges:
            if edge.get("relation") == "contains":
                target = edge.get("target")
                if target:
                    contained.add(target)

        self._classes_by_name: dict[str, list[dict]] = {}
        for node in all_nodes:
            if not node.get("_callable_class") or node.get("id") not in contained:
                continue
            self._classes_by_name.setdefault(_key(node.get("label", "")), []).append(node)

        self._methods: dict[tuple[str, str], str] = {}
        # Method NAMES per class, and the class each method belongs to. Both exist for scoped
        # calls: graphify records `Helper::format()` with the SCOPE as the callee and drops the
        # method name entirely, so the only way back to `format` without re-parsing PHP here is
        # to ask the graph which methods that class declares and let the type source check each
        # candidate against the line it really came from.
        self._method_names: dict[str, list[str]] = {}
        self._owner_of: dict[str, str] = {}
        for edge in all_edges:
            if edge.get("relation") != "method":
                continue
            owner, member = edge.get("source"), edge.get("target")
            member_node = node_by_id.get(member)
            if owner and member_node is not None:
                label = member_node.get("label", "")
                self._methods[(owner, _key(label))] = member
                self._owner_of[member] = owner
                # `.format()` is the label; the bare name is what a call site writes.
                self._method_names.setdefault(owner, []).append(str(label).strip(". ()"))

        self._parents: dict[str, list[str]] = {}
        for edge in all_edges:
            if edge.get("relation") == "inherits":
                child, parent = edge.get("source"), edge.get("target")
                if child and parent:
                    self._parents.setdefault(child, []).append(parent)

        # Origin maps. `contains` puts a class in its file; a method hangs off its class, so it
        # is folded through to the owning class's file. `imports` targets the imported CLASS
        # node directly for PHP `use` statements, which is what makes "can the caller see this
        # class" answerable from the graph rather than guessed from a path.
        self._file_of: dict[str, str] = {}
        for edge in all_edges:
            if edge.get("relation") == "contains":
                self._file_of[edge.get("target")] = edge.get("source")
        for method_nid, owner in self._owner_of.items():
            owner_file = self._file_of.get(owner)
            if owner_file is not None:
                self._file_of.setdefault(method_nid, owner_file)

        self._imported_by: dict[str, set[str]] = {}
        for edge in all_edges:
            if edge.get("relation") in ("imports", "imports_from"):
                self._imported_by.setdefault(edge.get("source"), set()).add(edge.get("target"))

        # `mixes_in` runs from the using class to the trait, so this maps a trait to its users.
        self._node_by_id = node_by_id
        self._mixed_into: dict[str, list[str]] = {}
        for edge in all_edges:
            trait, user = edge.get("target"), edge.get("source")
            if edge.get("relation") == "mixes_in" and trait and user:
                self._mixed_into.setdefault(trait, []).append(user)
        # Built on first use: the route pass builds this index too and never asks.
        self._callables_by_file: dict[str, list[tuple[int | None, str]]] | None = None
        # The same, keyed by real path, for a caller named by a parser's file spelling.
        self._callables_by_real: dict[str, list[tuple[int | None, str]]] | None = None
        self._caller_scopes: dict[str, tuple[str, ...]] = {}

    def method_node(self, class_fqn: str, method: str) -> str | None:
        class_node = self._class_node(class_fqn)
        if class_node is None:
            return None
        return self._methods.get((class_node["id"], _key(method)))

    def method_node_for(self, caller_nid: str, class_fqn: str, method: str) -> str | None:
        """`method_node`, with the caller's own visibility as the tie-breaker and the gate.

        A short-name match is not evidence the caller can see the matched class: a call that a
        type source resolved to `Vendor\\Lib\\Emails` must not bind to a project class that
        merely spells `Emails` the same way. graphify records enough to check rather than guess
        — `use` statements arrive as `imports` edges pointing straight at the class node — so a
        candidate is accepted when the caller's file imports it, when it is in the caller's own
        file, or when it is an ancestor of the caller's class (`parent::`).

        A PSR-4 path match is kept as a second, independent signal, because a class in the
        caller's own namespace needs no `use` and so produces no import edge. Refuse only when
        neither signal fires: the bar is graphify's own, an absent edge over a wrong one.
        """
        parts = _fqn_parts(class_fqn)
        if not parts:
            return None
        candidates = self._classes_by_name.get(_key(parts[-1]), [])
        if not candidates:
            return None

        visible = [c for c in candidates if self._visible_to(caller_nid, c["id"])]
        chosen = visible[0] if len(visible) == 1 else None
        if chosen is not None and self._outscored(chosen, candidates, parts[:-1]):
            # Visibility picked one class, but the namespace the type source proved points
            # at a different candidate more precisely (a parent `App\Legacy\Emails` is
            # visible; the property is typed `App\Mail\Emails`). Binding the visible one
            # would contradict the proof, so the call gets no edge.
            return None
        if chosen is None and not visible:
            chosen = self._class_node(class_fqn)
        if chosen is None:
            return None
        return self._methods.get((chosen["id"], _key(method)))

    def proved_node_for(
        self, caller_nid: str, target: CallTarget, repo_root: str = "."
    ) -> str | None:
        """The method node holding a proved target's body, or None.

        `method_node_for` lets visibility pick among same-named classes, so a proof of
        `Vendor\\Lib\\Cache::get` binds to a project `Cache` declared in the caller's own file.
        A proof that names its declaring file is bound in that file only: the one class of that
        short name there, and its method of that name. A proof of a class no parsed file
        declares binds nothing. A proof without a file has nothing to check against and keeps
        the visibility lookup.
        """
        if target.outside_corpus:
            return None
        if not target.declaring_file:
            return self.method_node_for(caller_nid, target.class_fqn, target.method)
        parts = _fqn_parts(target.class_fqn)
        if not parts:
            return None
        here = _real(target.declaring_file, repo_root)
        in_file = [
            c
            for c in self._classes_by_name.get(_key(parts[-1]), [])
            if _real(str(c.get("source_file") or ""), repo_root) == here
        ]
        if len(in_file) != 1:
            return None
        return self._methods.get((in_file[0]["id"], _key(target.method)))

    def callable_at(
        self, source_file: str, lines: tuple[int, ...], repo_root: str = "."
    ) -> str | None:
        """The one callable node of that file starting on one of `lines`, else None.

        A parser names a call's innermost function, method or closure by where it starts; the
        graph carries the same start line on each callable node. Two nodes on those lines (a
        one-line class, nested closures) cannot be told apart, so neither is the answer.
        """
        if self._callables_by_real is None:
            self._callables_by_real = {}
            for path, found in self._callables().items():
                if path:
                    self._callables_by_real.setdefault(_real(path, repo_root), []).extend(found)
        wanted = set(lines)
        matched = [
            nid
            for start, nid in self._callables_by_real.get(_real(source_file, repo_root), ())
            if start in wanted
        ]
        return matched[0] if len(matched) == 1 else None

    @staticmethod
    def _outscored(chosen: dict, candidates: list[dict], namespace: list[str]) -> bool:
        def overlap(node: dict) -> int:
            return _tail_overlap(namespace, _path_parts(node.get("source_file", ""))[:-1])

        own = overlap(chosen)
        return any(c is not chosen and overlap(c) > own for c in candidates)

    def _visible_to(self, caller_nid: str, class_nid: str) -> bool:
        caller_class = self._owner_of.get(caller_nid, caller_nid)
        if class_nid == caller_class:
            return True
        caller_file = self._file_of.get(caller_nid) or self._file_of.get(caller_class)
        if caller_file is not None:
            if self._file_of.get(class_nid) == caller_file:
                return True
            if class_nid in self._imported_by.get(caller_file, ()):
                return True
        return class_nid in self._with_ancestors([caller_class])

    def method_node_in_file(self, source_file: str, class_fqn: str, method: str) -> str | None:
        """`method_node`, resolved against a class declared in a known file.

        A route attribute sits ON the controller class, so the file it was read from names the
        class exactly — stronger evidence than any namespace-to-path guess, and it is what makes
        the lookup work for the many real projects whose directory layout does not mirror their
        namespace. Falls back to the namespace match when the file holds no such class.
        """
        parts = _fqn_parts(class_fqn)
        if not parts:
            return None
        in_file = [
            c
            for c in self._classes_by_name.get(_key(parts[-1]), [])
            if c.get("source_file") == source_file
        ]
        chosen = in_file[0] if len(in_file) == 1 else self._class_node(class_fqn)
        if chosen is None:
            return None
        return self._methods.get((chosen["id"], _key(method)))

    def engine_calls(self, all_edges: list[dict]) -> list[EngineCall]:
        """`calls` edges graphify's engine bound by bare name to a node in the caller's file.

        The engine writes them with no score and no marker (`extractors/engine.py`, the
        `seen_call_pairs` block); graphify's other passes score theirs and ours carry
        `EDGE_MARKER`. The target is recognised by its node and file, never by label shape: an
        anonymous class's method is labelled `getData()`, without the dot. A free function
        carries the same schema (contained by its file, no dot, no `method` edge), so such a
        target is listed with `target_is_method` False for a parser to settle.
        """
        found: list[EngineCall] = []
        for edge in all_edges:
            if edge.get("relation") != "calls" or EDGE_MARKER in edge:
                continue
            if "confidence_score" in edge:
                continue
            path = str(edge.get("source_file") or "")
            if not path.endswith(".php"):
                continue
            caller = self._node_by_id.get(edge.get("source"))
            target = self._node_by_id.get(edge.get("target"))
            if caller is None or target is None or target.get("_callable_class"):
                continue
            if str(target.get("source_file") or "") != path or _is_closure(target):
                continue
            method = _name(target)
            if not method:
                continue
            found.append(
                EngineCall(
                    caller_nid=caller["id"],
                    target_nid=target["id"],
                    method=method,
                    source_file=path,
                    source_location=str(edge.get("source_location") or ""),
                    caller_location=str(caller.get("source_location") or ""),
                    edge=edge,
                    target_is_method=self.is_method_node(target["id"]),
                    target_location=str(target.get("source_location") or ""),
                )
            )
        return found

    def is_method_node(self, nid: str) -> bool:
        """Whether `nid` is a class's method: a `method` edge owns it, or it is labelled `.m()`.

        Never a class node. An anonymous class's method (`getData()`, no dot, no `method`
        edge) cannot be told from a function and is not one.
        """
        node = self._node_by_id.get(nid)
        if node is None or node.get("_callable_class") or _is_closure(node):
            return False
        return nid in self._owner_of or bool(_DOTTED_METHOD.match(str(node.get("label", ""))))

    def method_bound_calls(self, all_edges: list[dict]) -> list[MethodBoundCall]:
        """`calls` edges from PHP lines to a method node, written by graphify and not by us."""
        found: list[MethodBoundCall] = []
        for edge in all_edges:
            if edge.get("relation") != "calls" or EDGE_MARKER in edge:
                continue
            path = str(edge.get("source_file") or "")
            if not path.endswith(".php"):
                continue
            source, target = edge.get("source"), edge.get("target")
            if not isinstance(source, str) or not isinstance(target, str):
                continue
            if not self.is_method_node(target):
                continue
            method = _name(self._node_by_id[target])
            if not method:
                continue
            found.append(
                MethodBoundCall(
                    caller_nid=source,
                    target_nid=target,
                    method=method,
                    source_file=path,
                    source_location=str(edge.get("source_location") or ""),
                    edge=edge,
                )
            )
        return found

    def names_node(self, target_nid: str, target: CallTarget, repo_root: str = ".") -> bool | None:
        """Whether a proved target is the body `target_nid` is, by file and class.

        False when the proof's body is in another file, or is another class's method in the
        same file. None when that cannot be told: no declaring file, or no single class of
        that short name in the file (`class@anonymous`, two namespaces sharing one name).
        """
        node = self._node_by_id.get(target_nid)
        if node is None or not target.declaring_file or not node.get("source_file"):
            return None
        here = _real(str(node["source_file"]), repo_root)
        if _real(target.declaring_file, repo_root) != here:
            return False
        parts = _fqn_parts(target.class_fqn)
        if not parts:
            return None
        in_file = [
            c
            for c in self._classes_by_name.get(_key(parts[-1]), [])
            if _real(str(c.get("source_file") or ""), repo_root) == here
        ]
        if len(in_file) != 1:
            return None
        method_nid = self._methods.get((in_file[0]["id"], _key(target.method)))
        if method_nid is None:
            return None
        return method_nid == target_nid

    def method_missing_in_declaring_file(self, target: CallTarget, repo_root: str = ".") -> bool:
        """Whether the proof's declaring file holds its class and no method node of that name.

        The shape of a method a docblock `@method` or `__call` provides: the type engine names
        the class, the graph has the class and no node for the body. Never True for a proof
        without a file or with two classes of that short name in the file.
        """
        parts = _fqn_parts(target.class_fqn)
        if not parts or not target.declaring_file:
            return False
        here = _real(target.declaring_file, repo_root)
        in_file = [
            c
            for c in self._classes_by_name.get(_key(parts[-1]), [])
            if _real(str(c.get("source_file") or ""), repo_root) == here
        ]
        return len(in_file) == 1 and (in_file[0]["id"], _key(target.method)) not in self._methods

    def closure_starts_on(self, caller_nid: str, source_location: str) -> bool:
        """Whether the caller is a closure starting on this line.

        A type engine files a closure's calls under the method around it, so the method's own
        calls on the closure's first line arrive with the same caller and cannot be told apart.
        """
        node = self._node_by_id.get(caller_nid)
        line = _line(source_location)
        return (
            node is not None
            and _is_closure(node)
            and line is not None
            and _line(node.get("source_location")) == line
        )

    def owner_class(self, method_nid: str) -> str | None:
        """The class node a method node hangs off, by its `method` edge."""
        return self._owner_of.get(method_nid)

    def caller_scope(self, caller_nid: str) -> tuple[str, ...]:
        """`Class::method` spellings a type engine may report for a call inside this caller.

        PHPStan names the class it analysed the body in, so a trait method is reported under
        each class using it and a closure under the method it sits in. `()` means no class
        method can be named, and a source matching on file and line must then refuse.
        """
        found = self._caller_scopes.get(caller_nid)
        if found is None:
            found = self._scope_of(caller_nid)
            self._caller_scopes[caller_nid] = found
        return found

    def _scope_of(self, caller_nid: str) -> tuple[str, ...]:
        node = self._node_by_id.get(caller_nid)
        if node is None:
            return ()
        method_nid = self._enclosing_callable(node) if _is_closure(node) else caller_nid
        if method_nid is None:
            return ()
        method = _name(self._node_by_id[method_nid])
        owner = self._owner_of.get(method_nid)
        if owner is None:
            # A class lost to a parse error, an anonymous class's method: the graph cannot name
            # the class, so the method goes alone and the source must prove the class.
            return (f"::{method}",) if method and self._name_unique_in_file(method_nid) else ()
        if self._short_name_shared_in_file(owner):
            # `A\Foo` and `B\Foo` in one file both label `Foo`; a record cannot be told apart.
            return ()
        return tuple(f"{label}::{method}" for label in self._class_and_users(owner))

    def _callables(self) -> dict[str, list[tuple[int | None, str]]]:
        """Every callable but a class, per file, with its start line (None when unknown)."""
        if self._callables_by_file is None:
            self._callables_by_file = {}
            for nid, node in self._node_by_id.items():
                if not node.get("_callable") or node.get("_callable_class"):
                    continue
                path = str(node.get("source_file") or "")
                start = _line(node.get("source_location"))
                self._callables_by_file.setdefault(path, []).append((start, nid))
        return self._callables_by_file

    def _name_unique_in_file(self, nid: str) -> bool:
        node = self._node_by_id[nid]
        key = _key(_name(node))
        same = [
            other
            for _start, other in self._callables().get(str(node.get("source_file") or ""), ())
            if _key(_name(self._node_by_id[other])) == key
        ]
        return same == [nid]

    def _short_name_shared_in_file(self, class_nid: str) -> bool:
        node = self._node_by_id.get(class_nid, {})
        home = self._file_of.get(class_nid)
        return any(
            other["id"] != class_nid and self._file_of.get(other["id"]) == home
            for other in self._classes_by_name.get(_key(node.get("label", "")), ())
        )

    def _enclosing_callable(self, closure: dict) -> str | None:
        """The nearest non-closure callable starting at or above the closure, in its file.

        graphify links a closure to its file only. A closure outside every method body gets no
        PHPStan record at all, so the nearest method is the one a record can name; a tie is
        refused, and so is a line one callable may end on and the next starts on.
        """
        line = _line(closure.get("source_location"))
        if line is None:
            return None
        above = [
            (start, nid)
            for start, nid in self._callables().get(str(closure.get("source_file") or ""), ())
            if start is not None and start <= line and not _is_closure(self._node_by_id[nid])
        ]
        if not above:
            return None
        nearest = max(start for start, _ in above)
        at_nearest = [nid for start, nid in above if start == nearest]
        if len(at_nearest) != 1:
            return None
        if nearest == line and len(above) > 1:
            # The graph carries no end lines: `} public function b() { fn () => ...` may be
            # the last line of the method above as well as the first of `b`.
            return None
        return at_nearest[0]

    def caller_owns_line(self, caller_nid: str, source_location: str) -> bool:
        """Whether a call on this line placed in the caller's method is in the caller's body.

        True only when no other callable starts between the caller's first line and this one.
        A closure nested in the caller, or a neighbour on a one-line class, would start there,
        and a type engine names the same enclosing method for all of them.
        """
        node = self._node_by_id.get(caller_nid)
        line = _line(source_location)
        start = _line(node.get("source_location")) if node is not None else None
        if node is None or line is None or start is None or start > line:
            return False
        return not any(
            other != caller_nid and (begins is None or start <= begins <= line)
            for begins, other in self._callables().get(str(node.get("source_file") or ""), ())
        )

    def _class_and_users(self, owner: str) -> list[str]:
        """The owner's label, then every class reaching it through `mixes_in`, transitively."""
        order, seen = [owner], {owner}
        for current in order:
            for user in self._mixed_into.get(current, ()):
                if user not in seen:
                    seen.add(user)
                    order.append(user)
        labels: list[str] = []
        for nid in order:
            label = str(self._node_by_id.get(nid, {}).get("label", ""))
            if label and label not in labels:
                labels.append(label)
        return labels

    def scope_methods(self, caller_nid: str, scope: str) -> list[str]:
        """Method names a scoped call `<scope>::?()` from this caller could be naming.

        Candidates, not answers. Each one is offered to a type source, which reads the call
        site's own line and refuses every name that is not written there, so a wrong candidate
        costs a lookup and produces nothing. An empty list means the scope names no class this
        graph knows, which is how an ordinary function call (`trim`, `error_log`) — recorded by
        graphify in the same shape as a scoped call — is filtered out without special-casing.
        """
        classes = self._scope_classes(caller_nid, scope)
        names: list[str] = []
        seen: set[str] = set()
        for class_nid in classes:
            for name in self._method_names.get(class_nid, ()):
                if name and name not in seen:
                    seen.add(name)
                    names.append(name)
        return names

    def _scope_classes(self, caller_nid: str, scope: str) -> list[str]:
        key = _key(scope)
        if key in ("self", "static"):
            owner = self._owner_of.get(caller_nid)
            # Inherited methods are callable through `self::` too, so the ancestry is included.
            return self._with_ancestors([owner]) if owner else []
        if key == "parent":
            owner = self._owner_of.get(caller_nid)
            return self._with_ancestors(self._parents.get(owner, [])) if owner else []
        # A written class name: every class that spells it. Ambiguity is harmless here because
        # the candidate is a method NAME, and the source resolves the class itself from the
        # file's own namespace and `use` statements.
        return self._with_ancestors(
            [
                n["id"]
                for n in self._classes_by_name.get(
                    _key(_fqn_parts(scope)[-1] if _fqn_parts(scope) else ""), []
                )
            ]
        )

    def _with_ancestors(self, class_nids: list[str]) -> list[str]:
        out: list[str] = []
        queue = list(class_nids)
        seen: set[str] = set()
        while queue:
            nid = queue.pop(0)
            if not nid or nid in seen:
                continue
            seen.add(nid)
            out.append(nid)
            queue.extend(self._parents.get(nid, ()))
        return out

    def _class_node(self, class_fqn: str) -> dict | None:
        parts = _fqn_parts(class_fqn)
        if not parts:
            return None
        namespace, short = parts[:-1], parts[-1]
        candidates = self._classes_by_name.get(_key(short), [])
        if not candidates:
            return None

        # Directories only: the file stem is the class name and matching it against the
        # namespace would score every candidate the same.
        scored = [
            (_tail_overlap(namespace, _path_parts(c.get("source_file", ""))[:-1]), c)
            for c in candidates
        ]
        best = max(score for score, _ in scored)
        winners = [c for score, c in scored if score == best]
        if len(winners) != 1:
            # Two project classes share a short name and the namespace did not separate them.
            # Picking either is a coin flip, and a wrong call edge is worse than a missing one.
            return None

        # A namespace of two or more segments must show up in the file path, because a FQN
        # from outside the indexed tree (`Doctrine\ORM\EntityManager`) otherwise binds to
        # whatever project class happens to share its last segment — a unique match, and
        # wrong. A single-segment namespace is exempt: the PSR-4 root (`App\`) maps to the
        # source directory (`src/`) and never appears as a directory itself.
        # One shared segment is not enough either: `Vendor\Lib\Emails` against
        # `src/Lib/Emails.php` overlaps by one and is still foreign. Every segment but the
        # PSR-4 root has to be on the path.
        if len(namespace) >= 2 and best < len(namespace) - 1:
            return None
        return winners[0]


class GraphEdgeSink:
    """Appends `calls` edges to graphify's edge list.

    Deduplicates against the pairs already in the graph, the way graphify's own member-call
    resolvers do: the shared cross-file pass may already have connected the same two nodes by
    another route, and a second edge would double that pair's weight in every consumer.
    """

    def __init__(self, all_edges: list[dict], index: GraphNodeIndex | None = None) -> None:
        self._all_edges = all_edges
        self._index = index
        self._pairs = {(e.get("source"), e.get("target")) for e in all_edges}
        self._class_calls = {
            (e.get("source"), e.get("target")) for e in all_edges if e.get("relation") == "calls"
        }
        self.added = 0

    def add_call(self, caller_nid: str, callee_nid: str, target: CallTarget) -> None:
        if (caller_nid, callee_nid) in self._pairs:
            return
        self._pairs.add((caller_nid, callee_nid))
        edge = {
            "source": caller_nid,
            "target": callee_nid,
            "relation": "calls",
            "context": "call",
            "confidence": target.confidence.value,
            "confidence_score": _CONFIDENCE_SCORE[target.confidence],
            "source_file": target.site.source_file,
            "source_location": target.site.source_location,
            "weight": 1.0,
            EDGE_MARKER: EDGE_ORIGIN,
            "_via": target.via,
        }
        # `Helper::format()` already produced a coarse caller -> Helper-the-CLASS edge, because
        # graphify records the scope as the callee and resolves that name to the class node. Our
        # method-level edge is a second, narrower edge between different endpoints, so neither
        # dedup nor removal applies — a consumer counting `calls` edges will see both. Naming
        # the coarse edge here is what lets it collapse the pair instead of double-counting it.
        owner = self._index.owner_class(callee_nid) if self._index is not None else None
        if owner is not None and (caller_nid, owner) in self._class_calls:
            edge["_refines"] = owner
        self._all_edges.append(edge)
        self.added += 1

    def remove_edges(self, edges: list) -> int:
        """Take these exact edge objects out of the list, in place, and say how many went.

        Slice assignment, so whoever holds the list sees the removal. Matched by identity: two
        equal dicts are two edges, and only the one handed over is meant.
        """
        doomed = {id(edge) for edge in edges}
        kept = [edge for edge in self._all_edges if id(edge) not in doomed]
        removed = len(self._all_edges) - len(kept)
        if removed:
            self._all_edges[:] = kept
            self._pairs = {(e.get("source"), e.get("target")) for e in kept}
            self._class_calls = {
                (e.get("source"), e.get("target")) for e in kept if e.get("relation") == "calls"
            }
        return removed


def holds_build_edges(all_edges: list) -> bool:
    """Whether `all_edges` is the list graphify's build keeps, not a scratch copy of it.

    A full build hands resolvers its own list (extract.py, `run_language_resolvers(paths,
    per_file, all_nodes, all_edges)`). An incremental one hands a copy with the unchanged
    corpus appended and keeps only the copy's tail, so a removal there is silently lost. The
    only proof available is the driver's caller holding this same object as `all_edges`;
    anything else, a test harness included, answers False.
    """
    frame = inspect.currentframe()
    try:
        while frame is not None:
            if (
                frame.f_code.co_name == "run_language_resolvers"
                and frame.f_globals.get("__name__") == "graphify.resolver_registry"
            ):
                caller = frame.f_back
                return caller is not None and caller.f_locals.get("all_edges") is all_edges
            frame = frame.f_back
        return False
    finally:
        del frame


def _method_key(label: object) -> str:
    # The key core matches a callee by: `.get()` -> `get`, case-insensitive like PHP.
    return str(label or "").strip().removeprefix(".").removesuffix("()").lower()


class SiteProofs:
    """graphify-php `calls` edges by the site they prove: (caller, location, method key).

    A method target is named by its node label; a vendor stub target by `_external_target`
    (`Class::method`). Two proofs at one site (a union receiver) keep the smallest target id,
    so the choice does not depend on edge order. Core's withheld edges are matched against it.
    """

    def __init__(self, all_nodes: list[dict], all_edges: list[dict]) -> None:
        self._label = {n.get("id"): n.get("label") for n in all_nodes if isinstance(n, dict)}
        self._index: dict[tuple, str] = {}
        for edge in all_edges:
            if edge.get(EDGE_MARKER) != EDGE_ORIGIN or edge.get("relation") != "calls":
                continue
            source, target = edge.get("source"), edge.get("target")
            if (
                not isinstance(source, str)
                or not isinstance(target, str)
                or not source
                or not target
            ):
                continue
            external = edge.get("_external_target")
            name = str(external).rsplit("::", 1)[-1] if external else self._label.get(target)
            key = (source, str(edge.get("source_location") or ""), _method_key(name))
            if key not in self._index or target < self._index[key]:
                self._index[key] = target

    def proof_for(self, edge: dict) -> tuple[str, str, str, str] | None:
        """(source, target, relation, proof target) when one of our edges proves `edge`'s site.

        Matched on the same caller, location and method name. None without a proof, or when
        `edge` has no usable target.
        """
        source, target = edge.get("source"), edge.get("target")
        key = (source, str(edge.get("source_location") or ""), _method_key(self._label.get(target)))
        proof = self._index.get(key)
        if proof is None or not isinstance(target, str) or not target:
            return None
        return source, target, str(edge.get("relation") or "calls"), proof


STUB_ID_PREFIX = "php_external_"


def _stub_nid(class_fqn: str) -> str:
    """One id per external class, derived from the FQN alone so every build agrees.

    `external: True` keeps the id global in `merge-graphs`, so the prefix must not collide with
    graphify's own project-class ids, which never start this way.
    """
    return STUB_ID_PREFIX + re.sub(r"[^a-z0-9_]", "_", class_fqn.lower().replace("\\", "_"))


class GraphStubSink:
    """Mints a body-less node per external declaring class and edges proven calls to it.

    The opt-in graphify core refuses for `calls` (phantom hubs): a `Doctrine\\ORM\\EntityManager`
    stub will carry hundreds of edges. One stub per CLASS, never per method, so the node count
    stays at the number of vendor classes the project touches; the method survives on the edge.
    """

    def __init__(self, all_nodes: list[dict], all_edges: list[dict]) -> None:
        self._all_nodes = all_nodes
        self._all_edges = all_edges
        self._by_id = {n.get("id") for n in all_nodes}
        self._pairs = {(e.get("source"), e.get("target")) for e in all_edges}
        self.nodes_added = 0
        self.edges_added = 0

    def node_for(self, class_fqn: str) -> str:
        nid = _stub_nid(class_fqn)
        if nid not in self._by_id:
            self._by_id.add(nid)
            # The same shape graphify core gives an import stub (build.py), so every consumer
            # that already handles those handles these.
            self._all_nodes.append(
                {
                    "id": nid,
                    "label": class_fqn,
                    "file_type": "concept",
                    "type": "external",
                    "external": True,
                    "source_file": "",
                    EDGE_MARKER: EDGE_ORIGIN,
                }
            )
            self.nodes_added += 1
        return nid

    def add_call(self, caller_nid: str, stub_nid: str, target: CallTarget) -> None:
        if (caller_nid, stub_nid) in self._pairs:
            return
        self._pairs.add((caller_nid, stub_nid))
        self._all_edges.append(
            {
                "source": caller_nid,
                "target": stub_nid,
                "relation": "calls",
                "context": "call",
                "confidence": target.confidence.value,
                "confidence_score": _CONFIDENCE_SCORE[target.confidence],
                "source_file": target.site.source_file,
                "source_location": target.site.source_location,
                "weight": 1.0,
                EDGE_MARKER: EDGE_ORIGIN,
                "_via": target.via,
                "_external_target": f"{target.class_fqn}::{target.method}",
            }
        )
        self.edges_added += 1


# A route declaration is not a call, so it needs a relation of its own. `routed_to` is already
# taken by messenger transport routing (config/messaging.py:22) and means something else
# entirely; reusing it would merge HTTP paths and message transports into one query.
ROUTE_RELATION = "handled_by"
ROUTE_NODE_KIND = "http_route"


def _route_nid(node_key: str) -> str:
    """A stable, readable id for a route declaration.

    The slug is for a human reading the graph; the digest is what guarantees identity, because
    two declarations differing only in punctuation (`/a-b` and `/a_b`) slug to the same string.
    `hashlib`, not `hash()`, so the id is the same in every process and every build.
    """
    slug = re.sub(r"[^a-zA-Z0-9]+", "_", node_key).strip("_").lower()[:80]
    digest = hashlib.blake2b(node_key.encode("utf-8"), digest_size=4).hexdigest()
    return f"route_{slug}_{digest}"


class GraphRouteSink:
    """Publishes one node and one edge per route declaration.

    Separate from `GraphEdgeSink` because it adds NODES, which no call-target path ever does:
    a route is a thing the graph did not previously contain, not a connection between two
    things it already had. That is also why it is worth a status record of its own — a layer
    that adds nothing looks exactly like a codebase with no routes.
    """

    def __init__(self, all_nodes: list[dict], all_edges: list[dict]) -> None:
        self._all_nodes = all_nodes
        self._all_edges = all_edges
        self._by_id = {n.get("id") for n in all_nodes}
        self._pairs = {(e.get("source"), e.get("target")) for e in all_edges}
        self.nodes_added = 0
        self.edges_added = 0

    def add_route(self, declaration, controller_nid: str | None) -> str | None:
        """Emit the declaration's node, and its edge when the controller method is in the graph.

        Returns the node id, or None when the declaration carries no path at all and so has
        nothing to label a node with.
        """
        path = declaration.path or declaration.method_path
        if not path:
            return None

        nid = _route_nid(declaration.node_key)
        if nid not in self._by_id:
            self._by_id.add(nid)
            self._all_nodes.append(
                {
                    "id": nid,
                    "label": path,
                    "source_file": declaration.source_file,
                    "source_location": f"L{declaration.line}",
                    "file_type": "code",
                    EDGE_MARKER: EDGE_ORIGIN,
                    "_kind": ROUTE_NODE_KIND,
                    "route_name": declaration.name or "",
                    "http_methods": list(declaration.methods),
                    # A path composed from only one half is a usable partial, not a whole answer,
                    # and a reader ranking routes needs to know which it is looking at.
                    "route_complete": declaration.path is not None,
                }
            )
            self.nodes_added += 1

        if controller_nid and (nid, controller_nid) not in self._pairs:
            self._pairs.add((nid, controller_nid))
            self._all_edges.append(
                {
                    "source": nid,
                    "target": controller_nid,
                    "relation": ROUTE_RELATION,
                    "context": "route",
                    "confidence": Confidence.EXTRACTED.value,
                    "confidence_score": 1.0,
                    "source_file": declaration.source_file,
                    "source_location": f"L{declaration.line}",
                    "weight": 1.0,
                    EDGE_MARKER: EDGE_ORIGIN,
                    "_via": "attribute",
                }
            )
            self.edges_added += 1
        return nid
